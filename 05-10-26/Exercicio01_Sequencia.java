public class Exercicio01_Sequencia {
    public static void main (String[] args) {
        
        for (int cont = 100; cont >= 1; cont--) {
            if (cont > 1) {
                System.out.print(cont + ", ");
            } else {
                System.out.println(cont);
            }
        }
    }
}