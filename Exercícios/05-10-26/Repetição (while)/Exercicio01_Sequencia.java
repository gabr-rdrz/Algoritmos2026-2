public class Exercicio01_Sequencia {
    public static void main(String[] args) {
        
        int contador = 100;
        while (contador <= 200) {

            if (contador < 200) {
                System.out.print(contador + ", ");
            } else {
                System.out.println(contador);
            }
            contador++;
        }
    }
}
